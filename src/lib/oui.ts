/**
 * Looks up the vendor name for a MAC address.
 * @param mac - colon-separated lowercase MAC address (e.g. "aa:bb:cc:dd:ee:ff")
 * @returns vendor name or undefined if not found
 */
export function lookupVendor(mac: string): string | undefined {
  if (!mac || mac.length < 8) return undefined;
  // Normalise to lowercase for lookup
  const prefix = mac.toLowerCase().slice(0, 8);
  return OUI_TABLE[prefix];
}
